type DemoBidInput = {
  id: string;
  bidCode: string;
  tenderId: string;
  supplierId: string;
  status: SupplierBid["status"];
  submittedAt: string;
  unitPrices: number[];
  deliveryTime: string;
  paymentTerms: string;
  warrantyPolicy?: string;
  note?: string;
  itemMeta?: Partial<BidItem>[];
};

function demoTender(id: string): AdminTender {
  const tender = DEMO_TENDERS.find((item) => item.id === id);
  if (!tender) throw new Error(`Missing demo tender: ${id}`);
  return tender;
}

function demoSupplier(id: string): SupplierAccount {
  const supplier = DEMO_SUPPLIER_ACCOUNTS.find((item) => item.id === id);
  if (!supplier) throw new Error(`Missing demo supplier: ${id}`);
  return supplier;
}

function makeDemoBid(input: DemoBidInput): SupplierBid {
  const tender = demoTender(input.tenderId);
  const supplier = demoSupplier(input.supplierId);
  const items = tender.items.map((item, index): BidItem => {
    const unitPrice = input.unitPrices[index] ?? 0;
    return {
      id: `${input.id}-item-${index + 1}`,
      tenderItemId: item.id,
      itemName: item.itemName,
      specification: item.specification,
      quantity: item.quantity,
      unit: item.unit,
      unitPrice,
      amount: unitPrice * item.quantity,
      brand: input.itemMeta?.[index]?.brand,
      origin: input.itemMeta?.[index]?.origin,
      deliveryTime: input.itemMeta?.[index]?.deliveryTime,
      note: input.itemMeta?.[index]?.note,
    };
  });
  const totalAmount = items.reduce((sum, item) => sum + item.amount, 0);

  return {
    id: input.id,
    bidCode: input.bidCode,
    tenderId: tender.id,
    tenderCode: tender.code,
    tenderTitle: tender.title,
    tenderName: tender.title,
    supplierId: supplier.id,
    supplierName: supplier.companyName,
    supplierEmail: supplier.email,
    supplierPhone: supplier.phone,
    status: input.status,
    submittedAt: input.submittedAt,
    createdAt: input.submittedAt,
    totalAmount,
    totalPrice: totalAmount,
    deliveryTime: input.deliveryTime,
    paymentTerms: input.paymentTerms,
    warrantyPolicy: input.warrantyPolicy,
    note: input.note,
    items,
  };
}

